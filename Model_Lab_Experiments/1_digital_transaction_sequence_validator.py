t = {
    ("START", "initiated"): "INITIATED",
    ("INITIATED", "authenticated"): "AUTHENTICATED",
    ("AUTHENTICATED", "processed"): "PROCESSED",
    ("PROCESSED", "completed"): "COMPLETED"
}

s = "START"
events = input("Enter events: ").lower().split()

for e in events:
    if (s, e) in t:
        s = t[(s, e)]
        print(s)
    else:
        s = "REJECTED"
        break

print("VALID" if s == "COMPLETED" else "INVALID")