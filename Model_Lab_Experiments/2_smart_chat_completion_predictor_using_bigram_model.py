from collections import Counter

text = "hello how are you hello how are they"
words = text.split()
b = Counter(zip(words, words[1:]))

w = input("Enter word: ")
total = sum(c for (a, _), c in b.items() if a == w)

if total == 0:
    print("Word not found")
else:
    for (a, n), c in sorted(b.items(),
                            key=lambda x: x[1], reverse=True):
        if a == w:
            print(n, round(c/total, 2))