import re

s = input("Enter expression: ")

tokens = re.findall(r'∀|∃|[A-Za-z]+|[∧∨¬→()]', s)

print("Components:", tokens)

if tokens and tokens.count("(") == tokens.count(")") and "(" in tokens:
    print("Expression is Valid")
else:
    print("Syntax Error")